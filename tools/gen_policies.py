"""
Generate php-app/app/policies.php from the published policy pages.

The legal copy is lifted, not rewritten. Each live page is one Elementor
heading (the page title) and one text-editor widget (the document). This
takes the widget's inner HTML, drops every attribute except href, and writes
it out as a PHP string. Then it re-extracts the words from both sides and
refuses to write anything if a single word differs.

    python tools/gen_policies.py                 # fetch from detox-locator.com
    python tools/gen_policies.py path/to/dir     # use saved <slug>.html files
"""

from __future__ import annotations

import html
import re
import sys
import urllib.request
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "php-app" / "app" / "policies.php"

PAGES = {
    "privacy-policy": "Privacy Policy",
    "hipaa-policy": "HIPAA Policy",
}

KEEP = {"h1", "h2", "h3", "h4", "p", "ul", "ol", "li", "strong", "b", "em", "i", "a", "br"}
VOID = {"br"}


def fetch(slug: str, src: str | None) -> str:
    if src:
        return (Path(src) / f"{slug}.html").read_text(encoding="utf-8")
    req = urllib.request.Request(
        f"https://detox-locator.com/{slug}/",
        headers={"User-Agent": "Mozilla/5.0 (policy-sync)"},
    )
    with urllib.request.urlopen(req, timeout=30) as res:
        return res.read().decode("utf-8")


def widget_html(page: str) -> str:
    """Inner HTML of the one text-editor widget in the page body."""
    start = page.index('data-elementor-type="wp-page"')
    end = page.index("elementor-location-footer", start)
    body = page[start:end]
    m = re.search(r'elementor-widget-text-editor".*?<div class="elementor-widget-container">', body, re.S)
    if not m:
        raise SystemExit("text-editor widget not found")
    rest = body[m.end():]

    # Walk to the matching </div>.
    depth, i = 1, 0
    for tag in re.finditer(r"<(/?)div\b[^>]*>", rest):
        depth += -1 if tag.group(1) else 1
        if depth == 0:
            i = tag.start()
            break
    return rest[:i]


class Clean(HTMLParser):
    """Keep structure and inline emphasis; drop classes, styles and wrappers."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=False)
        self.out: list[str] = []

    def handle_starttag(self, tag, attrs):
        if tag not in KEEP:
            return
        if tag == "a":
            href = dict(attrs).get("href", "")
            ext = "" if "detox-locator.com" in href or href.startswith(("/", "#", "mailto:", "tel:")) else ' target="_blank" rel="noopener"'
            self.out.append(f'<a href="{html.escape(href, quote=True)}"{ext}>')
        elif tag in VOID:
            self.out.append(f"<{tag}>")
        else:
            self.out.append(f"<{tag}>")

    def handle_endtag(self, tag):
        if tag in KEEP and tag not in VOID:
            self.out.append(f"</{tag}>")

    def handle_data(self, data):
        self.out.append(data)

    def handle_entityref(self, name):
        self.out.append(f"&{name};")

    def handle_charref(self, name):
        self.out.append(f"&#{name};")


def clean(fragment: str) -> str:
    p = Clean()
    p.feed(fragment)
    out = "".join(p.out)
    out = out.replace(" ", "&nbsp;")
    out = re.sub(r"<p>\s*</p>", "", out)
    out = re.sub(r"[ \t]*\n[ \t\n]*", "\n", out).strip()
    # One block-level element per line, so diffs of the generated file read.
    out = re.sub(r"\s*(<(?:h[1-4]|p|ul|ol|li)>)", r"\n\1", out).strip()
    return out


def words(fragment: str) -> list[str]:
    text = re.sub(r"<[^>]+>", " ", fragment)
    text = html.unescape(text).replace(" ", " ").replace("​", "")
    return text.split()


def php_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main() -> None:
    src = sys.argv[1] if len(sys.argv) > 1 else None
    docs = {}
    for slug, title in PAGES.items():
        raw = widget_html(fetch(slug, src))
        body = clean(raw)
        a, b = words(raw), words(body)
        if a != b:
            for n, (x, y) in enumerate(zip(a, b)):
                if x != y:
                    raise SystemExit(f"{slug}: word {n} differs: {x!r} vs {y!r}")
            raise SystemExit(f"{slug}: word count {len(a)} vs {len(b)}")
        print(f"{slug}: {len(b)} words, identical to the published page")
        docs[slug] = (title, body)

    lines = [
        "<?php",
        "/**",
        " * Policy copy, lifted verbatim from the published pages.",
        " *",
        " * GENERATED by tools/gen_policies.py from /privacy-policy/ and",
        " * /hipaa-policy/ on detox-locator.com. The generator compares every word",
        " * against the source and refuses to write if one differs. Do not edit the",
        " * wording here — it is vetted legal copy. Regenerate instead.",
        " *",
        " * Bodies are trusted HTML (headings, lists, emphasis, links) and are",
        " * printed unescaped. Nothing user-supplied belongs in this file.",
        " *",
        " * @package dl-locator",
        " */",
        "",
        "declare( strict_types = 1 );",
        "",
        "defined( 'DL_ROOT' ) || exit;",
        "",
        "/** @return array<string,array{title:string,html:string}> */",
        "function dl_policies(): array {",
        "\treturn array(",
    ]
    for slug, (title, body) in docs.items():
        lines.append(f"\t\t{php_string(slug)} => array(")
        lines.append(f"\t\t\t'title' => {php_string(title)},")
        lines.append(f"\t\t\t'html'  => {php_string(body)},")
        lines.append("\t\t),")
    lines += ["\t);", "}", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
